// One-time fix for store links created before accented letters were handled
// (e.g. "JANOSÉ" got /business/janos instead of /business/janose).
//
// Run once from the backend folder:
//   node scripts/fixAccentedSlugs.js
//
// Safe by design: it ONLY changes a slug that exactly matches what the old
// generator would have produced from the business name. A link a vendor chose
// themselves is never touched. Only names containing non-ASCII letters are checked.

import dns from "node:dns";
dns.setServers(["8.8.8.8", "8.8.4.4"]);

import dotenv from "dotenv";
dotenv.config();

import { connectDB } from "../src/db.js";
import Business from "../src/models/Business.js";
import { generateUniqueSlug, slugify } from "../src/services/storeSlug.js";

// The previous slugify, kept here only to recognise auto-generated slugs.
const oldSlugify = (text) =>
  String(text)
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

const run = async () => {
  await connectDB();

  const businesses = await Business.find({ slug: { $exists: true, $ne: "" } });
  let fixed = 0;

  for (const business of businesses) {
    if (!/[^\x00-\x7F]/.test(business.name)) continue; // plain-ASCII names were never affected
    const oldBase = oldSlugify(business.name) || "store";
    const isAutoGenerated = business.slug === oldBase || business.slug.startsWith(`${oldBase}-`);
    if (!isAutoGenerated) continue;
    if (slugify(business.name) === oldBase) continue; // new generator gives the same result

    const slug = await generateUniqueSlug(business.name, business._id);
    console.log(`  ✓ "${business.name}": /business/${business.slug} -> /business/${slug}`);
    business.slug = slug;
    await business.save();
    fixed += 1;
  }

  console.log(`Done. ${fixed} link(s) updated.`);
  process.exit(0);
};

run().catch((error) => {
  console.error("Fix failed:", error);
  process.exit(1);
});